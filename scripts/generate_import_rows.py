#!/usr/bin/env python3
"""Choose the builtin rows that are compiled at import.

A fresh process pays for each builtin row on the first scan that searches it.
The rows below are the ones nearly every first scan needs, ordered by how many
of the spec fixtures (and the two benign samples) need them, cut at a budget
of source characters that keeps the import at or below v4.4.0.

    python scripts/generate_import_rows.py          # rewrite the table
    python scripts/generate_import_rows.py --check  # fail when it is stale
"""

import asyncio
import json
import logging
import sys
import warnings
from collections import Counter
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
TARGET = ROOT / "guard_core" / "_builtin_import_rows.py"
FIXTURE_CASES = ROOT / "specs" / "fixtures" / "cases"
IMPORT_ROW_BUDGET_CHARS = 3000
_MAX_TEXT_CHARS = 2000
_PIECE_WIDTH = 80
_SINGLE_LINE_WIDTH = 83
_BENIGN = (
    "Quarterly report for the finance team: revenue grew while churn fell, "
    "see the dashboard and the attached notes. "
)
_BENIGN_SIZES = (200, 7251)


class _State:
    pass


class _Request:
    url_path = "/probe"
    url_scheme = "https"
    url_full = "https://test/probe"
    method = "GET"
    client_host = "203.0.113.9"

    def __init__(self, text: str) -> None:
        self._state = _State()
        self.query_params = {"q": text}
        self.headers = {"user-agent": "attack-probe/1.0", "accept": "*/*"}

    def url_replace_scheme(self, scheme: str) -> str:
        return self.url_full.replace("https", scheme, 1)

    async def body(self) -> bytes:
        return b""

    @property
    def state(self) -> _State:
        return self._state

    @property
    def scope(self) -> dict[str, object]:
        return {}


def _fixture_texts() -> list[str]:
    found: set[str] = set()

    def walk(node: object) -> None:
        if isinstance(node, str):
            found.add(node)
        elif isinstance(node, dict):
            for value in node.values():
                walk(value)
        elif isinstance(node, list):
            for value in node:
                walk(value)

    for case_file in sorted(FIXTURE_CASES.glob("*.json")):
        walk(json.loads(case_file.read_text()))
    return sorted(text for text in found if 0 < len(text) < _MAX_TEXT_CHARS)


def _benign_texts() -> list[str]:
    return [(_BENIGN * (size // len(_BENIGN) + 1))[:size] for size in _BENIGN_SIZES]


async def _rows_each_first_scan_needs(texts: list[str]) -> Counter[str]:
    from guard_core.handlers._suspatterns_lazy_rows import COMPILED_BUILTIN_PATTERNS
    from guard_core.models import SecurityConfig
    from guard_core.utils import detect_penetration_attempt

    config = SecurityConfig(enable_redis=False)
    needed: Counter[str] = Counter()
    for text in texts:
        COMPILED_BUILTIN_PATTERNS.clear()
        request: Any = _Request(text)
        await detect_penetration_attempt(request, config)
        needed.update(list(COMPILED_BUILTIN_PATTERNS))
    COMPILED_BUILTIN_PATTERNS.clear()
    return needed


def chosen_rows(budget: int = IMPORT_ROW_BUDGET_CHARS) -> tuple[str, ...]:
    from guard_core.handlers._suspatterns_pattern_table import _PATTERN_DEFINITIONS

    warnings.simplefilter("ignore")
    logging.disable(logging.CRITICAL)
    texts = _benign_texts() + _fixture_texts()
    needed = asyncio.run(_rows_each_first_scan_needs(texts))
    position = {
        source: index for index, (source, _c, _k) in enumerate(_PATTERN_DEFINITIONS)
    }
    ordered = sorted(needed, key=lambda source: (-needed[source], position[source]))
    chosen: list[str] = []
    spent = 0
    for source in ordered:
        if spent + len(source) > budget:
            continue
        chosen.append(source)
        spent += len(source)
    return tuple(chosen)


def _quoted(text: str) -> str:
    escaped = text.replace("\\", "\\\\")
    if escaped.count('"') <= escaped.count("'"):
        return '"' + escaped.replace('"', '\\"') + '"'
    return "'" + escaped.replace("'", "\\'") + "'"


def _literal_lines(row: str) -> list[str]:
    if len(_quoted(row)) <= _SINGLE_LINE_WIDTH:
        return [f"    {_quoted(row)}"]
    pieces: list[str] = []
    start = 0
    while start < len(row):
        end = start + 1
        while end < len(row) and len(_quoted(row[start : end + 1])) <= _PIECE_WIDTH:
            end += 1
        pieces.append(_quoted(row[start:end]))
        start = end
    return ["    (", *[f"        {piece}" for piece in pieces], "    )"]


def render(rows: tuple[str, ...]) -> str:
    lines = [
        "# Generated by scripts/generate_import_rows.py, do not edit by hand.",
        "IMPORT_COMPILED_ROWS: tuple[str, ...] = (",
    ]
    for row in rows:
        literal = _literal_lines(row)
        literal[-1] += ","
        lines += literal
    lines.append(")")
    return "\n".join(lines) + "\n"


def main() -> int:
    if "--budget" in sys.argv[1:]:
        budget = int(sys.argv[sys.argv.index("--budget") + 1])
        sys.stdout.write(render(chosen_rows(budget)))
        return 0
    rows = chosen_rows()
    if "--check" in sys.argv[1:]:
        from guard_core._builtin_import_rows import IMPORT_COMPILED_ROWS

        if IMPORT_COMPILED_ROWS == rows:
            print("OK: the import row table is up to date")
            return 0
        print(
            "FAIL: the import row table is stale, run scripts/generate_import_rows.py"
        )
        return 1
    TARGET.write_text(render(rows))
    return 0


if __name__ == "__main__":
    sys.exit(main())
