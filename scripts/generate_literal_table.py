#!/usr/bin/env python3
from pathlib import Path

from guard_core.handlers._suspatterns_inline_matches import _BUILTIN_ROW_FLAGS
from guard_core.handlers._suspatterns_linear_path import _BUCKET_MIN_CHARS, _row_for
from guard_core.handlers._suspatterns_linear_path_source import (
    flattened,
    mandatory_characters,
    mandatory_key,
    row_pieces,
    row_spans,
    unbalanced_parenthesis_spans,
    without_spans,
)
from guard_core.handlers._suspatterns_literals import (
    parse_required_literals,
    source_digest,
)
from guard_core.handlers._suspatterns_pattern_table import _PATTERN_DEFINITIONS
from guard_core.handlers._suspatterns_tail_buckets import (
    alternation_layout,
    split_alternation,
)

TARGET = (
    Path(__file__).resolve().parent.parent
    / "guard_core"
    / "handlers"
    / "_suspatterns_literal_table.py"
)

MANDATORY_TARGET = TARGET.with_name("_suspatterns_linear_mandatory_table.py")

SPLIT_TARGET = TARGET.with_name("_suspatterns_linear_split_table.py")


def render_tail_splits() -> str:
    entries = {}
    for source, _contexts, _category in _PATTERN_DEFINITIONS:
        split = row_pieces(source)
        for piece in () if split is None else map(flattened, split[0][1:]):
            removed = unbalanced_parenthesis_spans(piece)
            tail = without_spans(piece, removed)
            parts = split_alternation(tail) if len(tail) > _BUCKET_MIN_CHARS else None
            if parts is not None:
                entries[source_digest(piece)] = (
                    tuple(removed),
                    alternation_layout(tail, parts),
                )
    lines = [
        "BUILTIN_TAIL_SPLITS: dict[",
        "    str,",
        "    tuple[",
        "        tuple[_Span, ...],",
        "        tuple[int, int, tuple[int, ...], int],",
        "    ],",
        "] = {",
    ]
    lines += [f"    {key!r}: {value!r}," for key, value in sorted(entries.items())]
    lines.append("}")
    return "\n".join(lines) + "\n"


def render_splits() -> str:
    entries = {}
    for source, _contexts, _category in _PATTERN_DEFINITIONS:
        spans = row_spans(source)
        entries[source_digest(source)] = (
            None if spans is None else (tuple(spans[0]), tuple(spans[1]))
        )
    lines = [
        "# Generated by scripts/generate_literal_table.py, do not edit by hand.",
        "_Span = tuple[int, int]",
        "BUILTIN_ROW_SPANS: dict[",
        "    str, tuple[tuple[_Span, ...], tuple[_Span | None, ...]] | None",
        "] = {",
    ]
    lines += [f"    {key!r}: {value!r}," for key, value in sorted(entries.items())]
    lines.append("}")
    return "\n".join(lines) + "\n" + render_tail_splits()


def render_mandatory() -> str:
    entries = {}
    for source, _contexts, _category in _PATTERN_DEFINITIONS:
        row = _row_for(source, _BUILTIN_ROW_FLAGS)
        if row is not None:
            piece = row._raw_pieces[-1]
            groups = mandatory_characters(piece, _BUILTIN_ROW_FLAGS)
            entries[mandatory_key(piece, _BUILTIN_ROW_FLAGS)] = tuple(
                tuple(sorted(group)) for group in groups
            )
    lines = [
        "# Generated by scripts/generate_literal_table.py, do not edit by hand.",
        "BUILTIN_MANDATORY_CHARACTERS: dict[str, tuple[tuple[str, ...], ...]] = {",
    ]
    lines += [f"    {key!r}: {value!r}," for key, value in sorted(entries.items())]
    lines.append("}")
    return "\n".join(lines) + "\n"


def render() -> str:
    entries = {
        source_digest(source): parse_required_literals(source)
        for source, _contexts, _category in _PATTERN_DEFINITIONS
    }
    lines = [
        "# Generated by scripts/generate_literal_table.py, do not edit by hand.",
        "BUILTIN_REQUIRED_LITERALS: dict[str, tuple[str, ...]] = {",
    ]
    lines += [f"    {key!r}: {value!r}," for key, value in sorted(entries.items())]
    lines.append("}")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    TARGET.write_text(render())
    MANDATORY_TARGET.write_text(render_mandatory())
    SPLIT_TARGET.write_text(render_splits())
