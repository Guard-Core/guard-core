#!/usr/bin/env python3
from pathlib import Path

from guard_core.handlers._suspatterns_inline_matches import _BUILTIN_ROW_FLAGS
from guard_core.handlers._suspatterns_linear_path import _row_for
from guard_core.handlers._suspatterns_linear_path_source import (
    mandatory_characters,
    mandatory_key,
)
from guard_core.handlers._suspatterns_literals import (
    parse_required_literals,
    source_digest,
)
from guard_core.handlers._suspatterns_pattern_table import _PATTERN_DEFINITIONS

TARGET = (
    Path(__file__).resolve().parent.parent
    / "guard_core"
    / "handlers"
    / "_suspatterns_literal_table.py"
)

MANDATORY_TARGET = TARGET.with_name("_suspatterns_linear_mandatory_table.py")


def render_mandatory() -> str:
    entries = {}
    for source, _contexts, _category in _PATTERN_DEFINITIONS:
        row = _row_for(source, _BUILTIN_ROW_FLAGS)
        if row is not None:
            piece = row._raw_pieces[-1]
            groups = mandatory_characters(piece, _BUILTIN_ROW_FLAGS)
            entries[mandatory_key(piece, _BUILTIN_ROW_FLAGS)] = tuple(
                tuple(sorted(group)) for group in groups
            )
    lines = [
        "# Generated by scripts/generate_literal_table.py, do not edit by hand.",
        "BUILTIN_MANDATORY_CHARACTERS: dict[str, tuple[tuple[str, ...], ...]] = {",
    ]
    lines += [f"    {key!r}: {value!r}," for key, value in sorted(entries.items())]
    lines.append("}")
    return "\n".join(lines) + "\n"


def render() -> str:
    entries = {
        source_digest(source): parse_required_literals(source)
        for source, _contexts, _category in _PATTERN_DEFINITIONS
    }
    lines = [
        "# Generated by scripts/generate_literal_table.py, do not edit by hand.",
        "BUILTIN_REQUIRED_LITERALS: dict[str, tuple[str, ...]] = {",
    ]
    lines += [f"    {key!r}: {value!r}," for key, value in sorted(entries.items())]
    lines.append("}")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    TARGET.write_text(render())
    MANDATORY_TARGET.write_text(render_mandatory())
